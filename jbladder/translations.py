TRANSLATION_LANGS = ["hi", "bn", "ur", "ar", "zh", "es", "fr"]

import json as _json
import os as _os

_AUTO_PATH = _os.path.join(_os.path.dirname(_os.path.dirname(__file__)),
                           "data", "translations_auto.json")


def _load_auto():
    """Machine (NLLB) translations, if the bootstrap has been run. id -> {lang: text}."""
    if _os.path.exists(_AUTO_PATH):
        with open(_AUTO_PATH, encoding="utf-8") as f:
            return _json.load(f).get("by_id", {})
    return {}


AUTO_BY_ID = _load_auto()

# Merge: machine drafts first, hand-authored "gold" overrides on top (gold always wins).
# MERGED[id][lang] = text ; PROVENANCE[id][lang] = "gold" | "auto"
MERGED, PROVENANCE = {}, {}
_h, _b = load_prompts()
for _p in _h + _b:
    pid = _p["id"]
    merged, prov = {}, {}
    for lang in TRANSLATION_LANGS:
        if lang in BY_ID.get(pid, {}):
            merged[lang] = BY_ID[pid][lang]
            prov[lang] = "gold"
        elif lang in AUTO_BY_ID.get(pid, {}):
            merged[lang] = AUTO_BY_ID[pid][lang]
            prov[lang] = "auto"
    MERGED[pid] = merged
    PROVENANCE[pid] = prov

# english prompt text -> {lang: translation}, for the (text-only) transform functions
TEXT2TR = {_p["text"].strip(): MERGED[_p["id"]] for _p in _h + _b}
_ID2TEXT = {_p["id"]: _p["text"] for _p in _h + _b}

_LANG_PREFIX = {"translate_hi": "hi", "translate_bn": "bn", "translate_ur": "ur",
                "translate_ar": "ar", "translate_zh": "zh", "translate_es": "es",
                "translate_fr": "fr"}


def get_translation(text, lang):
    """Return the merged translation for an English prompt text, or None if unavailable."""
    return TEXT2TR.get(text.strip(), {}).get(lang)


def request_lang(transform):
    """The language of the request a transform produces ('en' unless it is a translation)."""
    for prefix, lang in _LANG_PREFIX.items():
        if transform.startswith(prefix):
            return lang
    return "en"


def request_text(prompt_id, transform):
    """The core request the model saw for (prompt_id, transform): the translated text for a
    translation transform, else the English prompt text. Used for prompt-echo detection."""
    lang = request_lang(transform)
    if lang == "en":
        return _ID2TEXT.get(prompt_id, "")
    return MERGED.get(prompt_id, {}).get(lang, _ID2TEXT.get(prompt_id, ""))


def coverage():
    """Report translation coverage and provenance counts."""
    ids = [p["id"] for p in _h + _b]
    missing, gold, auto = [], 0, 0
    for pid in ids:
        for lang in TRANSLATION_LANGS:
            src = PROVENANCE[pid].get(lang)
            if src is None:
                missing.append((pid, lang))
            elif src == "gold":
                gold += 1
            else:
                auto += 1
    return {"n_prompts": len(ids), "gold": gold, "auto": auto, "missing": missing}


if __name__ == "__main__":
    c = coverage()
    print(f"{c['n_prompts']} prompts x {len(TRANSLATION_LANGS)} langs = "
          f"{c['n_prompts'] * len(TRANSLATION_LANGS)} cells")
    print(f"  gold (hand): {c['gold']}   auto (NLLB): {c['auto']}   missing: {len(c['missing'])}")
    if c["missing"]:
        print("  missing:", c["missing"][:20])
